function sendMessage() {
const startTime = performance.now();
const inputField = document.getElementById("userInput");
const rawText = inputField.value.trim();
if (!rawText) return;
appendMessage(rawText, "user");
inputField.value = "";
const lang = document.getElementById("langSelect").value;
const lowerText = rawText.toLowerCase();
const cleanWords = lowerText.replace(/[?.,!]/g, "").split(/\s+/);
let reply = null;
const followUpWords = ["more", "detail", "details", "extra", "aur", "batao", "explain"];
if (lastTopic && cleanWords.some(w => followUpWords.includes(w)) && lowerText.length < 30) {
reply = lastTopic["more_" + lang];
}
if (!reply) {
for (let item of knowledgeBase) {
if (isFuzzyMatch(lowerText, item.keywords)) {
lastTopic = item;
reply = item[lang];
break;
}
}
}
if (!reply) {
const greetings = ["hi", "hello", "hey", "namaste", "hlo", "good morning", "good evening"];
if (cleanWords.some(w => greetings.includes(w))) {
reply = uiText[lang].greetingReply;
}
}
setTimeout(() => {
appendMessage(reply || uiText[lang].fallback, "bot");
const endTime = performance.now();
document.getElementById("respTime").innerText = "Response: " + (endTime - startTime).toFixed(1) + " ms";
}, 200);
}
