let lastTopic = null;
function getEditDistance(a, b) {
const matrix = [];
for (let i = 0; i <= b.length; i++) matrix[i] = [i];
for (let j = 0; j <= a.length; j++) matrix[j] = j;
for (let i = 1; i <= b.length; i++) {
for (let j = 1; j <= a.length; j++) {
if (b.charAt(i - 1) === a.charAt(j - 1)) {
matrix[i][j] = matrix[i - 1][j - 1];
} else {
matrix[i][j] = Math.min(
matrix[i - 1][j - 1] + 1,
matrix[i][j - 1] + 1,
matrix[i - 1][j] + 1
);
}
}
}
return matrix[b.length][a.length];
}
function isFuzzyMatch(userInput, keywords) {
if (keywords.some(kw => userInput.includes(kw))) return true;
const words = userInput.replace(/[?.,!]/g, "").split(/\s+/);
for (let word of words) {
if (word.length < 4) continue;
for (let kw of keywords) {
if (kw.length < 4) continue;
const maxAllowedErrors = kw.length >= 7 ? 2 : 1;
if (getEditDistance(word, kw) <= maxAllowedErrors) {
return true;
}
}
}
return false;
}
